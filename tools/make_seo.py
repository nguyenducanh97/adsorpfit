def splice(html, new):
    if START in html and END in html:
        a = html.index(START)
        b = html.index(END) + len(END)
        return html[:a] + new + html[b:]
    anchor = "  </section>\n</main>"
    assert anchor in html, "could not find the end of the guide section"
    return html.replace(anchor, new + "\n" + anchor, 1)


def sitemap():
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            '  <url>\n'
            '    <loc>%s</loc>\n'
            '    <changefreq>monthly</changefreq>\n'
            '    <priority>1.0</priority>\n'
            '  </url>\n'
            '</urlset>\n' % SITE)


def robots():
    return "User-agent: *\nAllow: /\n\nSitemap: %ssitemap.xml\n" % SITE


if __name__ == "__main__":
    os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    html = open("index.html", encoding="utf-8").read()
    out = splice(html, block())
    stale = out != html
    if "--check" in sys.argv:
        print("index.html is %s" % ("STALE, run tools/make_seo.py" if stale
                                    else "up to date with the model specs"))
        sys.exit(1 if stale else 0)
    if stale:
        open("index.html", "w", encoding="utf-8", newline="").write(out)
    open("sitemap.xml", "w", encoding="utf-8", newline="").write(sitemap())
    open("robots.txt", "w", encoding="utf-8", newline="").write(robots())
    print("index.html %s" % ("updated" if stale else "unchanged"))
    print("sitemap.xml and robots.txt written")
